/**
 * Writes `src/theme/font-faces.generated.ts`: the weights and italics Google Fonts has for each family in
 * `src/theme/font-picks.ts`, read from Google's own list. Run it after adding a family:
 *
 *   pnpm --filter @cutcraft/kit gen:fonts
 *
 * It needs the network (fonts.google.com). It fails when a picked family is not on Google Fonts.
 */
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { GOOGLE_PICKS } from "../src/theme/font-picks";

const SOURCE = "https://fonts.google.com/metadata/fonts";

interface Family {
  readonly family: string;
  /** Faces by key: "400", "700i". */
  readonly fonts: Readonly<Record<string, unknown>>;
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
// The list may start with a line that stops it being read as a script.
const text = (await response.text()).replace(/^\)\]\}'\n/, "");
const families = new Map((JSON.parse(text).familyMetadataList as Family[]).map((f) => [f.family, f]));

const rows: string[] = [];
const missing: string[] = [];
for (const { family } of GOOGLE_PICKS) {
  const found = families.get(family);
  if (!found) {
    missing.push(family);
    continue;
  }
  // Only what `googleFont()` can declare: 100, 200 … 900. A family's extra weights (Nunito's 1000) are left out.
  const keys = Object.keys(found.fonts).filter((k) => {
    const weight = Number.parseInt(k, 10);
    return weight >= 100 && weight <= 900 && weight % 100 === 0;
  });
  const weights = keys
    .filter((k) => /^\d+$/.test(k))
    .map(Number)
    .sort((a, b) => a - b);
  const italics = keys
    .filter((k) => /^\d+i$/.test(k))
    .map((k) => Number.parseInt(k, 10))
    .sort((a, b) => a - b);
  rows.push(`  ${JSON.stringify(family)}: { weights: [${weights.join(", ")}], italics: [${italics.join(", ")}] },`);
}
if (missing.length > 0) throw new Error(`not on Google Fonts: ${missing.join(", ")}`);

const out = `// Generated by scripts/gen-font-catalog.ts from ${SOURCE}. Do not edit; run \`pnpm --filter @cutcraft/kit gen:fonts\`.

/** The weights Google Fonts has for each picked family, upright and italic. */
export const GOOGLE_FACES: Readonly<Record<string, { readonly weights: readonly number[]; readonly italics: readonly number[] }>> = {
${rows.join("\n")}
};
`;
const file = fileURLToPath(new URL("../src/theme/font-faces.generated.ts", import.meta.url));
await writeFile(file, out);
// Written the way the repository's formatter leaves it, so a second run changes nothing.
execFileSync("pnpm", ["exec", "biome", "format", "--write", file], { stdio: "inherit" });
process.stdout.write(`${rows.length} families\n`);
